export const DICTIONARIES = { en, ar };

export function translate(lang, key, vars) {
    const dict = DICTIONARIES[lang] || en;
    const s = dict[key] ?? en[key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m)) : s;
}

const I18nContext = createContext({ lang: "en", t: (k, v) => translate("en", k, v), setLang: () => {} });

const readLang = () => {
    try {
        return localStorage.getItem("elzoz.lang") === "ar" ? "ar" : "en";
    } catch (e) {
        return "en";
    }
};

export function I18nProvider({ children }) {
    const [lang, setLangState] = useState(readLang);
    const setLang = useCallback((l) => {
        setLangState(l);
        try {
            localStorage.setItem("elzoz.lang", l);
        } catch (e) {
            /* storage unavailable */
        }
    }, []);
    const value = useMemo(() => ({ lang, setLang, rtl: lang === "ar", t: (k, v) => translate(lang, k, v) }), [lang, setLang]);
    return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
