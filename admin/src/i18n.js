export function translate(lang, key, vars = {}) {
    const s = (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key;
    return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined ? `{${k}}` : String(vars[k])));
}

/** Map an ApiError to a translated message. */
export function errorText(lang, e) {
    const code = e && e.code;
    const map = { invalid_grant: "invalid_credentials", invalid_credentials: "invalid_credentials" };
    const k = `err_${map[code] || code}`;
    if (STRINGS.en[k]) return translate(lang, k);
    return translate(lang, "err_generic", { message: (e && e.message) || String(e) });
}
